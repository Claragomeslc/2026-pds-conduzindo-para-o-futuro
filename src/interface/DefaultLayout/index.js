import Head from "next/head";
import { PageLayout, Header, Link, Text } from "@primer/react";
import styles from "./index.module.css";
import { callApi, useUser } from "interface/api";

// Menu do topo: muda os links conforme quem está logado
function Menu() {
  const { user } = useUser();

  async function logout() {
    await callApi("/api/v1/sessions", "DELETE");
    window.location.href = "/";
  }

  return (
    <Header>
      <Header.Item full>
        <Header.Link href="/">Conduzindo Para O Futuro</Header.Link>
      </Header.Item>
      <Header.Item>
        <Header.Link href="/habilitacao">Habilitação</Header.Link>
      </Header.Item>

      {!user && (
        <>
          <Header.Item>
            <Header.Link href="/login">Login</Header.Link>
          </Header.Item>
          <Header.Item>
            <Header.Link href="/cadastro">Cadastre-se</Header.Link>
          </Header.Item>
        </>
      )}

      {user && (
        <>
          <Header.Item>
            <Header.Link href="/instrutores">Instrutores</Header.Link>
          </Header.Item>
          <Header.Item>
            <Header.Link href="/aulas">Minhas aulas</Header.Link>
          </Header.Item>
          {user.role === "instructor" && (
            <>
              <Header.Item>
                <Header.Link href="/horarios">Meus horários</Header.Link>
              </Header.Item>
              <Header.Item>
                <Header.Link href="/perfil">Meu perfil</Header.Link>
              </Header.Item>
            </>
          )}
          <Header.Item>
            <Header.Link href="#" onClick={logout}>
              Sair ({user.username})
            </Header.Link>
          </Header.Item>
        </>
      )}
    </Header>
  );
}

// associates the dynamic name for the scoped class (generated by the CSS Modules pipeline)
// to the defined object keys
const contentWidthClasses = {
  small: styles.smallContent,
};

export default function DefaultLayout({
  children,
  metadata = {},
  contentWidth,
}) {
  const extraContentClassName = contentWidthClasses[contentWidth];

  return (
    <>
      <Head>
        <title>
          {metadata.title
            ? `${metadata.title} · Conduzindo Para O Futuro`
            : "Conduzindo Para O Futuro"}
        </title>

        {metadata.description && (
          <meta name="description" content={metadata.description} />
        )}
      </Head>

      <PageLayout.Header>
        <Menu />
      </PageLayout.Header>

      <PageLayout>
        <PageLayout.Content
          width={contentWidth}
          className={extraContentClassName}
        >
          {children}
        </PageLayout.Content>

        <PageLayout.Footer divider="line">
          <Text size="small">
            © {new Date().getFullYear()} Conduzindo Para O Futuro | Todos os
            direitos reservados. |{" "}
            <Link href="/suporte">Fale com o suporte</Link>
          </Text>
        </PageLayout.Footer>
      </PageLayout>
    </>
  );
}
